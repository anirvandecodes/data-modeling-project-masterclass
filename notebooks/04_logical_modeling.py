# MAGIC ## Seeing the Natural Keys We'll Replace
# MAGIC
# MAGIC Let's look at the natural keys that currently exist in our Bronze orders table. These are the `customer_id`, `product_id`, and `location_id` integers coming from the source system. We'll replace these with surrogate keys when building our Gold fact table.

# COMMAND ----------

# Show the natural keys in the orders table
print("Natural keys in workspace.bronze.orders:")
print("These integer IDs come from the source system.\n")
print("Problem: if the source system renumbers a customer (e.g., after a migration),")
print("all historical fact rows pointing to the old ID become orphaned.\n")

spark.sql("""
    SELECT
        order_id,
        customer_id,    -- natural key from source system
        product_id,     -- natural key from source system
        location_id,    -- natural key from source system
        order_date,
        total_amount
    FROM workspace.bronze.orders
    ORDER BY order_id
    LIMIT 10
""").show()

# COMMAND ----------

# Demonstrate the risk of natural keys:
# What happens if we count distinct customer_ids in orders vs actual customers?
print("Natural key integrity check: do all customer_ids in orders exist in customers?")
spark.sql("""
    SELECT
        COUNT(DISTINCT o.customer_id) AS distinct_customer_ids_in_orders,
        COUNT(DISTINCT c.customer_id) AS total_customers_in_master,
        COUNT(DISTINCT o.customer_id) - COUNT(DISTINCT c.customer_id) AS orphaned_ids
    FROM workspace.bronze.orders o
    LEFT JOIN workspace.bronze.customers c ON o.customer_id = c.customer_id
""").show()

# COMMAND ----------

# Show what the surrogate key WILL look like (preview of Gold layer design)
# We'll use MD5 of the source ID as a surrogate key
print("Preview: what the surrogate key approach looks like")
print("MD5 of the source customer_id becomes the stable, source-system-independent key\n")

spark.sql("""
    SELECT
        customer_id AS source_customer_id,
        md5(cast(customer_id AS STRING)) AS customer_key,
        first_name || ' ' || last_name AS full_name,
        email,
        segment
    FROM workspace.bronze.customers
    ORDER BY customer_id
    LIMIT 8
""").show(truncate=False)

