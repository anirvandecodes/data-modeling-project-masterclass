# MAGIC 2. **Date dimension added**: `order_date DATE` in the fact → `order_date_key INT` pointing to `dim_date`
# MAGIC 3. **Hierarchy flattened**: `category` and `subcategory` stay as separate columns in `dim_product` (no sub-table)
# MAGIC 4. **OLTP order table** → `fact_orders` (keeps measures, all FKs)
# MAGIC 5. **OLTP return table** → `fact_returns` (keeps measures, conformed FKs to same dims)
# MAGIC 6. **Full name denormalized**: `first_name + last_name` → single `full_name` column in `dim_customer`
