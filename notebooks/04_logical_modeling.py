# MAGIC
# MAGIC ### The Weak Entity: ORDER_LINE
# MAGIC
# MAGIC In a fully normalized OLTP model, we would also have an `ORDER_LINE` table — because one order can contain multiple products. Each line item would be a separate row.
# MAGIC
# MAGIC A **weak entity** is one that cannot be uniquely identified by its own attributes alone — it needs to borrow identity from a parent entity. ORDER_LINE has a composite PK: `(order_id, line_item_id)`. Without the `order_id`, `line_item_id = 1` is meaningless — it could belong to any order.
# MAGIC
# MAGIC In our simplified dataset, each order already contains a single product (one line item per order). So we don't need a separate ORDER_LINE table — the line item is embedded in the ORDER row. In production systems, you'd normalize this out.
