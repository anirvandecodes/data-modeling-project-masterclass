# MAGIC %md
# MAGIC ## Translating from OLTP to Analytical (Dimensional) Logical Model
# MAGIC
# MAGIC This translation is the core skill of dimensional modeling. Every OLTP table is either:
# MAGIC 1. A **transaction entity** → becomes a **fact table** (stores what happened + FKs + measures)
# MAGIC 2. A **reference entity** → becomes a **dimension table** (stores context + attributes)
# MAGIC
# MAGIC Here are the rules for the translation:
# MAGIC
# MAGIC | OLTP pattern | Dimensional equivalent | Reason |
# MAGIC |---|---|---|
# MAGIC | Transaction entity (ORDER) | **Fact table** | Records events; holds measures (amount, qty) |
# MAGIC | Reference entity (CUSTOMER, PRODUCT) | **Dimension table** | Provides context; describes WHO, WHAT, WHERE |
# MAGIC | Date attributes scattered everywhere | **Date dimension** (new table!) | Centralizes all calendar logic |
# MAGIC | Natural keys (customer_id=1042) | **Surrogate keys** | Stable, controlled, source-system independent |
# MAGIC | M:M bridge table | **The fact table IS the bridge** | fact_orders connects customer ↔ product |
# MAGIC | Hierarchy in one table (category/subcategory) | **Flattened into one wide dimension** | Eliminates joins in analytical queries |
# MAGIC | Normalized sub-tables (2NF/3NF) | **Denormalized into parent** | Fewer joins = faster analytics = happier analysts |
# MAGIC
# MAGIC ---

