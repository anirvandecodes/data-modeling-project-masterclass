# MAGIC ## What is a Logical Model?
# MAGIC
# MAGIC In Notebook 02, we built a **conceptual model**: boxes and lines, entities and relationships. No columns, no types — just the shape of the business domain.
# MAGIC
# MAGIC A **logical model** is the next level of detail. It takes the conceptual model and adds:
# MAGIC - Every **attribute** each entity tracks (the columns)
# MAGIC - **Data types** for each attribute (string, integer, date, decimal...)
# MAGIC - **Primary keys** (PKs) — the unique identifier for each row
# MAGIC - **Foreign keys** (FKs) — the links between tables
# MAGIC
# MAGIC Critically, a logical model is still **platform-independent**. We're not thinking about Delta Lake vs Parquet, or whether to partition by year. Those decisions come in the physical model (Notebook 06). Right now, we're modeling the data at a logical level that would work in any relational database.
# MAGIC
# MAGIC ---

# COMMAND ----------

# MAGIC %md
# MAGIC ## Primary Keys vs Foreign Keys
# MAGIC
# MAGIC These two concepts are the backbone of every relational model:
# MAGIC
# MAGIC ### Primary Key (PK)
# MAGIC A primary key is a column (or combination of columns) that **uniquely identifies each row** in a table. Rules:
# MAGIC - Must be unique — no two rows can have the same PK value
# MAGIC - Cannot be NULL — every row must have an identity
# MAGIC - Should never change — if a customer changes their email, that's fine. If they change their `customer_id`, that breaks everything pointing to them.
# MAGIC
# MAGIC ### Foreign Key (FK)
# MAGIC A foreign key is a column in one table that **references the primary key of another table**. It enforces referential integrity — you can't have an order referencing a customer that doesn't exist.
# MAGIC
# MAGIC ### Surrogate Keys vs Natural Keys
# MAGIC
# MAGIC | Type | Definition | Example | Risk |
# MAGIC |---|---|---|---|
# MAGIC | **Natural key** | A real-world identifier from the source system | `customer_id = 1042` | Can change if source system changes. Can collide across systems. |
# MAGIC | **Surrogate key** | A synthetic key generated by the data warehouse | `customer_key = 'md5(1042)'` | No business meaning, but stable and controlled |
# MAGIC
# MAGIC In dimensional modeling we **always use surrogate keys** in the Gold layer. We keep the original `source_id` as a regular column for traceability, but the joins use our surrogate key. We'll explain why this matters in Notebook 09 when we discuss Slowly Changing Dimensions.
